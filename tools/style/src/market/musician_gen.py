CONTACT = (13, 14)  # where the bow crosses the strings
SLOPE = -5 / 12
# per frame: elbow, hand (x of the frog), bow tip x, eyes shut
FRAMES = [((2, 17), 8, 20, False), ((2, 17), 5, 17, False), ((2, 16), 2, 14, False), ((2, 17), 5, 17, True)]


def line(x0, y0, x1, y1):
    pts, n = [], max(abs(x1 - x0), abs(y1 - y0))
    for i in range(n + 1):
        t = i / max(1, n)
        pts.append((round(x0 + (x1 - x0) * t), round(y0 + (y1 - y0) * t)))
    return pts


def bow_y(x):
    return round(CONTACT[1] + (x - CONTACT[0]) * SLOPE)


def frame(elbow, hx, tip, tap):
    g = [list(r) for r in BODY.splitlines()]
    hand = (hx, bow_y(hx))
    for a, b in (((4, 13), elbow), (elbow, hand)):  # sleeve, 2 px thick, shaded on the lower side
        for x, y in line(*a, *b):
            g[y][x] = "c"
            if y + 1 < 46 and g[y + 1][x] in ".vV":
                g[y + 1][x] = "C"
    for x, y in line(hx, bow_y(hx), tip, bow_y(tip)):
        g[y][x] = "L"
    x, y = hand
    for dx, dy in ((0, 0), (-1, 0), (0, 1), (-1, 1)):
        if 0 <= x + dx < 24:
            g[y + dy][x + dx] = "s" if (dx, dy) == (-1, 0) else "S"
    if tap:  # eyes shut, lost in the tune
        g[7][8:11] = list("hhs")
        g[7][13:16] = list("shh")
    return "\n".join("".join(r) for r in g)


def main():
    out = ["# Fiddler for the market, 24x46 per frame, front view, feet on row 44 (pivot 12,45), light from the top-left.",
           "# Frames: play x4 (bow down, middle, up, middle with eyes shut). GENERATED by musician_gen.py: edit that file.",
           LEGEND]
    for f in FRAMES:
        out += ["frame", frame(*f)]
    path = os.path.join(HERE, "musician.txt")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(path)


if __name__ == "__main__":
    main()
